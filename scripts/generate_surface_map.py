"""Generate the released-tool to fixed family-surface compatibility map.

The released inventory is frozen evidence.  This script joins it to the
live operation registry and startup plan, then writes the two reviewable
artifacts that explain every old tool's destination.

Run:  python -X utf8 scripts/generate_surface_map.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import _bootstrap  # noqa: E402


RELEASED = ROOT / "migration" / "released_tools_1.3.1.json"
MAP = ROOT / "migration" / "v1_to_v2.json"
TABLE = ROOT / "docs" / "surface_map.md"

REMOVED = frozenset({"enable_tools", "disable_tools"})
REMOVED_REASON = "removed: every operation is available from the start"


def _surface():
    _bootstrap.use_community()
    from kitchensink4ppt import registry, server  # noqa: F401
    from kitchensink4ppt.settings import Settings
    from kitchensink4ppt.surface import plan

    return registry, plan, plan.build(Settings(), registry.public_ops())


def render() -> tuple[str, dict]:
    """Return deterministic Markdown and JSON-compatible mapping data."""
    registry, plan, surface = _surface()
    released = json.loads(RELEASED.read_text(encoding="utf-8"))["tools"]
    tools: dict[str, dict[str, object | None]] = {}
    for old in sorted(released):
        if old in REMOVED:
            tools[old] = {
                "tool": None,
                "op": None,
                "args_changed": None,
                "reason": REMOVED_REASON,
            }
            continue
        if old not in registry.REGISTRY:
            raise plan.PlanError(
                f"released tool {old} has no op on the family surface"
            )
        destination = surface.op_tool.get(old)
        if destination is None or old not in surface.tools[destination].ops:
            raise plan.PlanError(
                f"released tool {old} is not visible on the family surface"
            )
        tools[old] = {
            "tool": destination,
            "op": old,
            "args_changed": None,
        }

    data = {
        "from": "kitchensink4ppt 1.3.1",
        "to": "kitchensink4ppt 2.0",
        "call_shape": "tool(op=<op>, args={...})",
        "tools": tools,
    }
    rows = [
        "| Released tool (1.3.1) | New tool | Op |",
        "|---|---|---|",
    ]
    for old, entry in tools.items():
        if entry["tool"] is None:
            rows.append(f"| `{old}` | (none) | {REMOVED_REASON} |")
        else:
            rows.append(f"| `{old}` | `{entry['tool']}` | `{entry['op']}` |")
    table = (
        "<!-- Generated by scripts/generate_surface_map.py; do not edit by hand. -->\n"
        + "\n".join(rows)
        + "\n"
    )
    return table, data


def main() -> None:
    table, data = render()
    TABLE.write_text(table, encoding="utf-8", newline="\n")
    MAP.write_text(
        json.dumps(data, indent=1, ensure_ascii=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(
        f"wrote {MAP.relative_to(ROOT)} ({len(data['tools'])} entries) and "
        f"{TABLE.relative_to(ROOT)}"
    )


if __name__ == "__main__":
    main()
