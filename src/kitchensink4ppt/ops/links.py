_ACTION_CUSTOM_SHOW = "ppaction://customshow"
_ACTION_MACRO = "ppaction://macro"
_ACTION_OLE = "ppaction://ole"
_ACTION_NONE = "ppaction://noaction"
#: Actions that work only through a relationship: open another deck, open a
#: file, run a program. Without an r:id they cannot do anything.
_REL_ACTIONS = (
    "ppaction://hlinkpres", "ppaction://hlinkfile", "ppaction://program",
)

_RUN_TAGS = (qn("a:r"), qn("a:fld"))
_RT_SLIDE_MASTER = (
    "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
    "/slideMaster"
)


def _action_args(action: str) -> dict[str, str]:
    """ppaction://name?a=1&b=2 -> {"a": "1", "b": "2"}, values as written."""
    out: dict[str, str] = {}
    for pair in action.partition("?")[2].split("&"):
        key, sep, value = pair.partition("=")
        if sep:
            out[key] = value
    return out


def _as_int(value):
    try:
        return int(value)
    except (TypeError, ValueError):
        return value


def _custom_shows(pkg: PptxPackage) -> dict:
    """{custom show id: name} from presentation.xml's p:custShowLst."""
    lst = pkg.presentation().find(qn("p:custShowLst"))
    if lst is None:
        return {}
    return {
        _as_int(show.get("id")): show.get("name", "")
        for show in lst.findall(qn("p:custShow"))
    }


def _classify_no_rel(record: dict, action: str, ctx: dict) -> dict | None:
    """A click or hover action with no relationship id. The slide jump
    without one is a broken link; a custom show, a macro and an OLE verb are
    actions PowerPoint runs without a relationship; "no action", an empty
    r:id with no action and the media control are not links."""
    if action == _ACTION_SLIDE_JUMP:
        # A neutered-but-not-removed jump (r:id gone): report as broken.
        record.update(kind="slide", broken=True,
                      problem="jump link has no relationship id")
        return record
    args = _action_args(action)
    if action.startswith(_ACTION_CUSTOM_SHOW):
        show_id = _as_int(args.get("id"))
        record.update(
            kind="custom_show",
            custom_show_id=show_id,
            show_and_return=args.get("return", "").lower() == "true",
        )
        name = ctx["shows"].get(show_id)
        if name is None:
            record.update(broken=True,
                          problem=f"custom show {show_id} is not in the deck")
        else:
            record["custom_show_name"] = name
        return record
    if action.startswith(_ACTION_MACRO):
        record.update(kind="macro", macro=args.get("name", ""))
        return record
    if action.startswith(_ACTION_OLE):
        record.update(kind="ole_verb", verb=_as_int(args.get("verb")))
        return record
    if action.startswith(_REL_ACTIONS):
        record.update(kind="external", action=action, broken=True,
                      problem="this action needs a relationship id and has none")
        return record
    if action and not action.startswith(_ACTION_NONE):
        record.update(kind="other", action=action)
        return record
    return None  # inert hlinkClick (e.g. r:id="" or ppaction://noaction)


def _classify(
    pkg: PptxPackage,
    part: str,
    el: etree._Element,
    rels: dict[str, dict],
    ctx: dict,
) -> dict | None:
    """One hlinkClick/hlinkHover element -> a report record, or None for
    media controls and inert empty links. An action that also plays a
    sound (an a:snd child) carries the sound's name, and "no action" with a
    sound, a click that only plays a sound, is listed as kind "sound"."""
    record = _classify_action(pkg, part, el, rels, ctx)
    snd = el.find(qn("a:snd"))
    if snd is None or (el.get("action") or "") == _ACTION_MEDIA:
        return record
    sound = snd.get("name") or "a sound"
    if record is None:
        record = {
            "trigger": "hover" if el.tag in HLINK_HOVER_QNAMES else "click",
            "tooltip": el.get("tooltip"),
            "broken": False,
            "kind": "sound",
        }
    record["sound"] = sound
    return record


def _classify_action(
    pkg: PptxPackage,
    part: str,
    el: etree._Element,
    rels: dict[str, dict],
    ctx: dict,
) -> dict | None:
    """The action of one hlinkClick/hlinkHover element -> a report record,
    or None for non-hyperlink affordances (media controls, inert empty
    links)."""
    action = el.get("action") or ""
    rid = el.get(_R_ID)
    if action == _ACTION_MEDIA:
        return None
    record: dict = {
        "trigger": "hover" if el.tag in HLINK_HOVER_QNAMES else "click",
        "tooltip": el.get("tooltip"),
        "broken": False,
    }
    if action.startswith(_ACTION_SHOW_JUMP):
        # ppaction://hlinkshowjump?jump=firstslide|lastslide|... (no rel)
        record["kind"] = "show_jump"
        record["jump"] = action.partition("jump=")[2] or action
        return record
    if not rid:
        return _classify_no_rel(record, action, ctx)
    if action and action != _ACTION_SLIDE_JUMP:
        # Run a program, open a file or another deck: the relationship holds
        # the path, and the action says what a click does with it.
        record["action"] = action
    rel = rels.get(rid)
    if rel is None:
        record.update(
            kind="slide" if action == _ACTION_SLIDE_JUMP else "external",
            broken=True,
            problem=f"relationship {rid} missing from the {ctx['rels_of']} rels",
        )
        return record
    if rel["external"]:
        record["kind"] = "external"
        record["url"] = rel["target"]
        if not rel["target"]:
            record.update(broken=True, problem=f"{rid} has an empty Target")
        return record
    if rel["type"] == RT_SLIDE:
        record["kind"] = "slide"
        dest = resolve_target(part, rel["target"])
        if not pkg.has_part(dest):
            record.update(
                broken=True,
                problem=f"{rid} targets missing part {dest}",
            )
        elif dest not in ctx["slide_parts"]:
            record.update(
                broken=True,
                problem=f"{rid} targets {dest}, which is not registered in "
                "the presentation (deleted slide?)",
            )
        else:
            record["target_part"] = dest
        return record
    record.update(
        kind="other",
        broken=True,
        problem=f"{rid} is internal with unexpected type {rel['type']}",
    )
    return record


def _scan_paragraphs(pkg, part, paragraphs, rels, ctx, base, out) -> None:
    """Run-level links in a list of a:p: ordinary runs and fields (a:fld,
    reported with its field type)."""
    for p_idx, p_el in enumerate(paragraphs):
        for run in p_el:
            if run.tag not in _RUN_TAGS:
                continue
            rpr = run.find(qn("a:rPr"))
            if rpr is None:
                continue
            for el in _existing_hlinks(rpr):
                record = _classify(pkg, part, el, rels, ctx)
                if record is None:
                    continue
                row = {**base, "paragraph": p_idx, "text": _run_text(run), **record}
                if run.tag == _RUN_TAGS[1]:
                    row["field"] = run.get("type") or "field"
                out.append(row)


def _scan_diagram(pkg, slide_part, frame, ctx, base, out) -> None:
    """Links on SmartArt node text, read from the diagram's data part (the
    part PowerPoint edits; the drawing part is its cached picture). node is
    the index set_diagram_text uses."""
    data_part = _diagram_data_part(pkg, slide_part, frame)
    if data_part is None or not pkg.has_part(data_part):
        return
    rels = _slide_rels_map(pkg, data_part)
    node = 0
    for pt in pkg.root(data_part).iter(f"{{{_DGM_NS}}}pt"):
        t = pt.find(f"{{{_DGM_NS}}}t")
        if t is None or pt.get("type", "node") not in DIAGRAM_TEXT_POINT_TYPES:
            continue
        _scan_paragraphs(pkg, data_part, t.findall(qn("a:p")), rels,
                         {**ctx, "rels_of": "SmartArt data"},
                         {**base, "node": node}, out)
        node += 1


def _scan_tree(pkg, part, head: dict, where: dict, ctx: dict, out: list) -> None:
    """Every link in one part's shape tree (a slide, its notes, a layout or a
    master): on shapes, on their text, in table cells and, on slides, in
    SmartArt nodes. where maps shape/text/table/diagram to the reported
    "where" value. A shape PowerPoint keeps in a compatibility wrapper (a
    text box, table or notes body that holds an equation) is read from the
    branch PowerPoint shows, as the other reads read it, so its links are
    listed once."""
    sp_tree = pkg.root(part).find(f"{qn('p:cSld')}/{qn('p:spTree')}")
    if sp_tree is None:
        return
    rels = _slide_rels_map(pkg, part)
    for elem, kind, _z, _parent in iter_shapes(sp_tree, wrapped=True):
        cnvpr = next(elem.iter(qn("p:cNvPr")), None)
        base = {
            **head,
            "shape_id": cnvpr_id(cnvpr),
            "shape_name": cnvpr.get("name", "") if cnvpr is not None else "",
        }
        if cnvpr is not None:
            for el in _existing_hlinks(cnvpr):
                record = _classify(pkg, part, el, rels, ctx)
                if record is not None:
                    out.append({**base, "where": where["shape"], **record})
        if kind == "table":
            tbl = table_element(elem)
            if tbl is None:
                continue
            for r, tr in enumerate(tbl.findall(qn("a:tr"))):
                for c, tc in enumerate(tr.findall(qn("a:tc"))):
                    _scan_paragraphs(
                        pkg, part, tc.findall(f"{qn('a:txBody')}/{qn('a:p')}"),
                        rels, ctx, {**base, "where": where["table"], "row": r, "col": c},
                        out)
            continue
        if kind == "diagram" and where.get("diagram"):
            _scan_diagram(pkg, part, elem, ctx, {**base, "where": where["diagram"]}, out)
            continue
        body = elem.find(qn("p:txBody"))
        if body is not None:
            _scan_paragraphs(pkg, part, body.findall(qn("a:p")), rels, ctx,
                             {**base, "where": where["text"]}, out)


def _master_of_layout(pkg: PptxPackage, layout: str) -> str | None:
    if not pkg.has_part(rels_name(layout)):
        return None
    for rel in pkg.rels_for(layout).getroot():
        if rel.get("Type") == _RT_SLIDE_MASTER:
            return resolve_target(layout, rel.get("Target", ""))
    return None


def list_hyperlinks(pkg: PptxPackage, scope=None) -> dict:
    """Every hyperlink and click action in scope (default: all slides):
    external URLs, jump-to-slide links, show jumps, custom shows, macros and
    OLE verbs, on shapes, on text runs and fields, in table cells, in
    SmartArt nodes and in each slide's notes; then the links on the layouts
    and masters those slides use, each listed once. Broken targets are
    flagged (missing rels, rels to deleted/unregistered slides, empty URLs,
    custom shows the deck lacks). A click that only plays a sound is listed
    as kind "sound", and any other action that plays one names it. Media
    playback controls and inert links are not listed. A shape PowerPoint
    keeps in a compatibility wrapper is read from the branch PowerPoint
    shows."""
    recs = slides_in_scope(pkg, scope)
    table = slide_table(pkg)
    part_index = {r["part"]: r for r in table}
    ctx = {
        "slide_parts": {r["part"] for r in table},
        "shows": _custom_shows(pkg),
        "rels_of": "slide",
    }
    on_slide = {"shape": "shape", "text": "text", "table": "table", "diagram": "diagram"}
    out: list[dict] = []
    layouts: list[str] = []
    for rec in recs:
        part = rec["part"]
        head = {"slide_index": rec["index"], "slide_id": rec["slide_id"]}
        _scan_tree(pkg, part, head, on_slide, ctx, out)
        npart = notes_part_for(pkg, part)
        if npart is not None and pkg.has_part(npart):
            _scan_tree(pkg, npart, head, dict.fromkeys(on_slide, "notes"),
                       {**ctx, "rels_of": "notes"}, out)
        layout = _layout_info(pkg, part)[0]
        if layout is not None and layout not in layouts and pkg.has_part(layout):
            layouts.append(layout)
    masters: list[str] = []
    for layout in layouts:
        _scan_tree(pkg, layout, {"layout": _layout_display_name(pkg, layout)},
                   {"shape": "layout", "text": "layout", "table": "layout"},
                   {**ctx, "rels_of": "layout"}, out)
        master = _master_of_layout(pkg, layout)
        if master is not None and master not in masters and pkg.has_part(master):
            masters.append(master)
    for master in masters:
        _scan_tree(pkg, master, {"master": _layout_display_name(pkg, master)},
                   {"shape": "master", "text": "master", "table": "master"},
                   {**ctx, "rels_of": "master"}, out)
    # Resolve jump targets to current indexes/ids for the report.
    for record in out:
        dest = record.pop("target_part", None)
        if dest is not None:
            dest_rec = part_index.get(dest)
            if dest_rec is not None:
                record["target_slide"] = {
                    "index": dest_rec["index"],
                    "slide_id": dest_rec["slide_id"],
                }
    broken = sum(1 for r in out if r["broken"])
    return {
        "hyperlinks": out,
        "count": len(out),
        "broken_count": broken,
        "slides_scanned": len(recs),
    }
