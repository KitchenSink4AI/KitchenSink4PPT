def _parse_target(target) -> dict:
    """Normalize the `target` selector: a shape id (int) links the whole
    shape; {"shape_id": N, "paragraph": P[, "start": S, "end": E]} links a
    text range (whole paragraph when start/end are omitted)."""
    if isinstance(target, bool):
        raise PptMcpError(f"invalid target {target!r}")
    if isinstance(target, int):
        return {"shape_id": target, "text": False}
    if isinstance(target, dict) and "shape_id" in target:
        known = {"shape_id", "paragraph", "start", "end"}
        unknown = set(target) - known
        if unknown:
            raise PptMcpError(
                f"unknown target key(s) {sorted(unknown)}; valid: "
                f"{sorted(known)}"
            )
        if "paragraph" not in target:
            if "start" in target or "end" in target:
                raise PptMcpError(
                    "start/end require a paragraph index in the target"
                )
            return {"shape_id": int(target["shape_id"]), "text": False}
        para = target["paragraph"]
        if not isinstance(para, int) or isinstance(para, bool) or para < 0:
            raise PptMcpError(
                f"paragraph must be a 0-based index, got {para!r}"
            )
        start = target.get("start")
        end = target.get("end")
        if (start is None) != (end is None):
            raise PptMcpError("pass both start and end, or neither")
        if start is not None:
            if not all(
                isinstance(v, int) and not isinstance(v, bool)
                for v in (start, end)
            ) or start < 0 or end <= start:
                raise PptMcpError(
                    f"start/end must be 0-based character offsets with "
                    f"start < end, got start={start!r} end={end!r}"
                )
        return {
            "shape_id": int(target["shape_id"]),
            "text": True,
            "paragraph": para,
            "start": start,
            "end": end,
        }
    raise PptMcpError(
        f"invalid target {target!r}: pass a shape id or "
        '{"shape_id": N, "paragraph": P, "start": S, "end": E}'
    )


def _cnvpr_of(elem: etree._Element) -> etree._Element:
    cnvpr = next(elem.iter(qn("p:cNvPr")), None)
    if cnvpr is None:
        raise UnsupportedStructure("shape has no cNvPr; refusing to guess")
    return cnvpr


def _paragraphs_of(elem: etree._Element) -> list[etree._Element]:
    body = elem.find(qn("p:txBody"))
    if body is None:
        raise UnsupportedStructure(
            "shape has no text body; a text-range hyperlink needs a shape "
            "with text (link the whole shape instead)"
        )
    return body.findall(qn("a:p"))


# ------------------------------------------------------------ run splitting


def _run_text(run: etree._Element) -> str:
    t = run.find(qn("a:t"))
    return t.text or "" if t is not None else ""


def _fld_len(fld: etree._Element) -> int:
    t = fld.find(qn("a:t"))
    return len(t.text or "") if t is not None else 0


def _paragraph_len(p_el: etree._Element) -> int:
    n = 0
    for child in p_el:
        tag = etree.QName(child).localname
        if tag == "r":
            n += len(_run_text(child))
        elif tag == "br":
            n += 1
        elif tag == "fld":
            n += _fld_len(child)
    return n


def _split_run(run: etree._Element, offset: int) -> etree._Element:
    """Split one a:r at a character offset; the ORIGINAL element keeps the
    tail and a deep copy carrying the head is inserted before it (both keep
    the run's rPr). Returns the original (tail) element."""
    t_el = run.find(qn("a:t"))
    text = t_el.text or ""
    head = copy.deepcopy(run)
    run.addprevious(head)
    head.find(qn("a:t")).text = text[:offset]
    t_el.text = text[offset:]
    return run


def _validate_range(p_el: etree._Element, start: int, end: int) -> None:
    """All range refusals, BEFORE any tree mutation: fld overlap, end past
    the paragraph, no covered run text."""
    pos = 0
    any_text = False
    for child in p_el:
        tag = etree.QName(child).localname
        if tag == "r":
            text = _run_text(child)
            r_start, r_end = pos, pos + len(text)
            pos = r_end
            if text and r_end > start and r_start < end:
                any_text = True
        elif tag == "br":
            pos += 1
        elif tag == "fld":
            f_start, f_end = pos, pos + _fld_len(child)
            pos = f_end
            if f_end > start and f_start < end:
                raise UnsupportedStructure(
                    "the text range overlaps a field (slide number/date); "
                    "fields regenerate their text, so linking across one is "
                    "refused. Narrow the range to plain text runs."
                )
    if end > pos:
        raise PptMcpError(
            f"range end {end} is past the paragraph's {pos} characters"
        )
    if not any_text:
        raise PptMcpError(
            f"range [{start}, {end}) covers no text runs in the paragraph"
        )


def _covered_runs(
    p_el: etree._Element, start: int, end: int
) -> list[etree._Element]:
    """The a:r elements exactly covering [start, end), splitting boundary
    runs in place. Call _validate_range first; this pass cannot fail."""
    covered: list[etree._Element] = []
    pos = 0
    for child in list(p_el):
        tag = etree.QName(child).localname
        if tag == "r":
            text = _run_text(child)
            r_start, r_end = pos, pos + len(text)
            pos = r_end
            if r_end <= start or r_start >= end or not text:
                continue
            run = child
            if r_start < start:
                run = _split_run(run, start - r_start)
                r_start = start
            if r_end > end:
                _split_run(run, end - r_start)
                run = run.getprevious()
            covered.append(run)
        elif tag == "br":
            pos += 1
        elif tag == "fld":
            pos += _fld_len(child)
    return covered


# ------------------------------------------------------------- rel plumbing


def _slide_rels_map(pkg: PptxPackage, part: str) -> dict[str, dict]:
    out: dict[str, dict] = {}
    if not pkg.has_part(rels_name(part)):
        return out
    for rel in pkg.rels_for(part).getroot():
        out[rel.get("Id")] = {
            "type": rel.get("Type"),
            "target": rel.get("Target", ""),
            "external": rel.get("TargetMode") == "External",
        }
    return out


def _external_rel(pkg: PptxPackage, part: str, url: str) -> str:
    for rid, rel in _slide_rels_map(pkg, part).items():
        if (
            rel["type"] == RT_HYPERLINK
            and rel["external"]
            and rel["target"] == url
        ):
            return rid
    return pkg.add_relationship(part, RT_HYPERLINK, url, external=True)


def _jump_rel(pkg: PptxPackage, part: str, dest_part: str) -> str:
    for rid, rel in _slide_rels_map(pkg, part).items():
        if (
            rel["type"] == RT_SLIDE
            and not rel["external"]
            and resolve_target(part, rel["target"]) == dest_part
        ):
            return rid
    target = posixpath.relpath(dest_part, posixpath.dirname(part))
    return pkg.add_relationship(part, RT_SLIDE, target.replace("\\", "/"))


def _gc_link_rels(pkg: PptxPackage, part: str, rids: set[str]) -> list[str]:
    """Drop hyperlink/jump rels from `rids` that nothing in the part
    references anymore. Only hyperlink- and slide-reltype rels are eligible
    (never layout/image/etc., whatever the caller passes)."""
    if not rids or not pkg.has_part(rels_name(part)):
        return []
    still_used: set[str] = set()
    for el in pkg.root(part).iter():
        for attr, value in el.attrib.items():
            if attr.startswith(f"{{{NSMAP['r']}}}") and value:
                still_used.add(value)
    removed: list[str] = []
    rels_root = pkg.rels_for(part).getroot()
    for rel in list(rels_root):
        rid = rel.get("Id")
        if (
            rid in rids
            and rid not in still_used
            and rel.get("Type") in (RT_HYPERLINK, RT_SLIDE)
        ):
            rels_root.remove(rel)
            removed.append(rid)
    if removed:
        pkg.mark_dirty(rels_name(part))
    return removed


# ------------------------------------------------------------ hlink surgery


def _existing_hlinks(container: etree._Element) -> list[etree._Element]:
    """Every hyperlink element directly inside one container, shape-level
    or run-level. Naming only the shape-level pair made a run's
    a:hlinkMouseOver invisible to set, remove and list alike."""
    return [el for el in container if el.tag in HLINK_QNAMES]


def _make_hlink(rid: str, action: str | None, tooltip: str | None):
    el = etree.Element(qn("a:hlinkClick"))
    el.set(_R_ID, rid)
    if action:
        el.set("action", action)
    if tooltip:
        el.set("tooltip", tooltip)
    return el


def _set_cnvpr_hlink(
    cnvpr: etree._Element, rid: str, action: str | None, tooltip: str | None
) -> list[str]:
    """Replace EVERY shape-level hyperlink; returns the rIds of the links
    replaced (for rel GC). Media playback affordances refuse.

    Click AND hover, because removing only a:hlinkClick left an old
    a:hlinkHover (the correct SHAPE-level hover element, inside p:cNvPr)
    beside the new link with its relationship still referenced, which is
    not the replacement set_hyperlink promises."""
    replaced: list[str] = []
    for el in _existing_hlinks(cnvpr):
        if el.get("action") == _ACTION_MEDIA:
            raise UnsupportedStructure(
                "this shape is a media frame (its click action plays the "
                "video/audio); refusing to overwrite the playback control "
                "with a hyperlink"
            )
        old = el.get(_R_ID)
        if old:
            replaced.append(old)
        cnvpr.remove(el)
    cnvpr.insert(0, _make_hlink(rid, action, tooltip))
    return replaced


def _set_run_hlink(
    run: etree._Element, rid: str, action: str | None, tooltip: str | None
) -> list[str]:
    """Replace EVERY hyperlink on one run; returns the rIds replaced.

    Click, the run-level hover element a:hlinkMouseOver, and the legacy
    a:hlinkHover spelling a run should never carry but might: all of them
    go before the new link is written, and each rId they held is returned
    so the relationship is dereferenced with them."""
    rpr = run.find(qn("a:rPr"))
    if rpr is None:
        rpr = etree.Element(qn("a:rPr"))
        run.insert(0, rpr)  # rPr is the first child of a:r
    replaced: list[str] = []
    for el in _existing_hlinks(rpr):
        old = el.get(_R_ID)
        if old:
            replaced.append(old)
        rpr.remove(el)
    ext = rpr.find(qn("a:extLst"))
    hl = _make_hlink(rid, action, tooltip)
    if ext is not None:
        ext.addprevious(hl)  # hlinkClick precedes extLst in CT_TextCharacterProperties
    else:
        rpr.append(hl)
    return replaced


