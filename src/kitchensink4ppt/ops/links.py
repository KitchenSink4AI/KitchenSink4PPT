def set_hyperlink(
    pkg: PptxPackage,
    slide,
    target,
    url: str | None = None,
    to_slide=None,
    tooltip: str | None = None,
) -> dict:
    """Set a hyperlink on a shape or a text range (replacing any link
    already there).

    target: shape id, or {"shape_id": N, "paragraph": P, "start": S,
    "end": E} for a text range (offsets in paragraph characters; omit
    start/end to link the whole paragraph). Exactly one destination:
    url (external, stored as a TargetMode="External" rel) or to_slide (a
    slide index or {"slide_id": N}; stored as the jump action plus an
    internal slide rel, the structure slide deletion knows how to neuter).
    tooltip: hover text.
    """
    if (url is None) == (to_slide is None):
        raise PptMcpError(
            "pass exactly one of url (external link) or to_slide "
            "(jump to a slide in this deck)"
        )
    rec = resolve_slide(pkg, slide)
    part = rec["part"]
    tgt = _parse_target(target)

    if url is not None:
        if not isinstance(url, str) or not url.strip():
            raise PptMcpError("url must be a non-empty string")
        url = url.strip()
        if ":" not in url:
            raise PptMcpError(
                f"url {url!r} has no scheme; pass a full URL "
                "(https://..., mailto:..., file:///...)"
            )
        action = None
        dest_info = {"url": url}
    else:
        dest = resolve_slide(pkg, to_slide)
        if dest["part"] == part:
            raise PptMcpError(
                f"to_slide resolves to the same slide (index {dest['index']});"
                " a slide cannot jump to itself"
            )
        action = _ACTION_SLIDE_JUMP
        dest_info = {
            "target_slide": {
                "index": dest["index"],
                "slide_id": dest["slide_id"],
            },
            # The jump target the way people count, and its title, so a
            # to_slide meant as "slide 3" (the fourth slide) shows itself
            # in the answer instead of hiding behind a 0-based index.
            "target_slide_number": dest["index"] + 1,
        }
        title = _slide_echo.clean_title(slide_title(pkg, dest["part"]))
        if title:
            dest_info["target_slide_title"] = title

    elem, _chain = _shapes._find_shape(pkg, part, tgt["shape_id"])

    # Validate everything that can refuse BEFORE any mutation.
    if not tgt["text"]:
        cnvpr = _cnvpr_of(elem)
        for existing in _existing_hlinks(cnvpr):
            if existing.get("action") == _ACTION_MEDIA:
                raise UnsupportedStructure(
                    "this shape is a media frame (its click action plays "
                    "the video/audio); refusing to overwrite the playback "
                    "control with a hyperlink"
                )
    else:
        paragraphs = _paragraphs_of(elem)
        if tgt["paragraph"] >= len(paragraphs):
            raise TargetNotFound(
                f"paragraph {tgt['paragraph']} out of range; shape "
                f"{tgt['shape_id']} has {len(paragraphs)} paragraphs"
            )
        p_el = paragraphs[tgt["paragraph"]]
        start = tgt["start"] if tgt["start"] is not None else 0
        end = tgt["end"] if tgt["end"] is not None else _paragraph_len(p_el)
        _validate_range(p_el, start, end)

    if url is not None:
        rid = _external_rel(pkg, part, url)
    else:
        rid = _jump_rel(pkg, part, dest["part"])

    replaced: list[str] = []
    runs_linked = 0
    if not tgt["text"]:
        replaced = _set_cnvpr_hlink(cnvpr, rid, action, tooltip)
        where = "shape"
    else:
        for run in _covered_runs(p_el, start, end):
            replaced.extend(_set_run_hlink(run, rid, action, tooltip))
            runs_linked += 1
        where = "text"
    pkg.mark_dirty(part)
    gc_removed = _gc_link_rels(pkg, part, set(replaced) - {rid})

    result = {
        "shape_id": tgt["shape_id"],
        "kind": "external" if url is not None else "slide",
        "where": where,
        "rid": rid,
        "tooltip": tooltip,
        "slide_index": rec["index"],
        "slide_id": rec["slide_id"],
        **dest_info,
    }
    if where == "text":
        result["runs_linked"] = runs_linked
    if gc_removed:
        result["replaced_rels_removed"] = gc_removed
    return result


def remove_hyperlink(pkg: PptxPackage, slide, target) -> dict:
    """Remove hyperlink(s) from a shape or text range. target: shape id
    (removes the shape-level link AND every run-level link in the shape) or
    {"shape_id": N, "paragraph": P[, "start": S, "end": E]} (removes links
    from the covered runs only). Orphaned hyperlink/jump rels are dropped.
    Media playback affordances are left alone."""
    rec = resolve_slide(pkg, slide)
    part = rec["part"]
    tgt = _parse_target(target)
    elem, _chain = _shapes._find_shape(pkg, part, tgt["shape_id"])

    removed_rids: set[str] = set()
    removed = 0

    def _strip(container: etree._Element) -> int:
        n = 0
        for el in _existing_hlinks(container):
            if el.get("action") == _ACTION_MEDIA:
                continue
            rid = el.get(_R_ID)
            if rid:
                removed_rids.add(rid)
            container.remove(el)
            n += 1
        return n

    if not tgt["text"]:
        removed += _strip(_cnvpr_of(elem))
        body = elem.find(qn("p:txBody"))
        if body is not None:
            for rpr in body.iter(qn("a:rPr")):
                removed += _strip(rpr)
    else:
        paragraphs = _paragraphs_of(elem)
        if tgt["paragraph"] >= len(paragraphs):
            raise TargetNotFound(
                f"paragraph {tgt['paragraph']} out of range; shape "
                f"{tgt['shape_id']} has {len(paragraphs)} paragraphs"
            )
        p_el = paragraphs[tgt["paragraph"]]
        start = tgt["start"] if tgt["start"] is not None else 0
        end = tgt["end"] if tgt["end"] is not None else _paragraph_len(p_el)
        _validate_range(p_el, start, end)
        for run in _covered_runs(p_el, start, end):
            rpr = run.find(qn("a:rPr"))
            if rpr is not None:
                removed += _strip(rpr)

    if removed:
        pkg.mark_dirty(part)
    gc_removed = _gc_link_rels(pkg, part, removed_rids)
    return {
        "shape_id": tgt["shape_id"],
        "removed": removed,
        "rels_removed": gc_removed,
        "slide_index": rec["index"],
        "slide_id": rec["slide_id"],
    }


